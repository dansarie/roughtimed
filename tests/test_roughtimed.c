START_TEST(test_check_ver) {
  uint8_t *buf = calloc(1000, 1);
  uint32_t vers[33] = {0};
  roughtime_result_t res = ROUGHTIME_SUCCESS;

  for (int i = 0; i < 33; i++) {
    vers[i] = htole32(i);
  }
  vers[31] = ROUGHTIME_VERSION;

  uint32_t size = 1000;
  res = create_roughtime_message(
      buf,
      &size,
      1,
      "VER",
      4 * 33,
      vers);
  ck_assert(res == ROUGHTIME_SUCCESS);

  roughtime_header_t header = {0};
  res = parse_roughtime_header(buf, size, &header);
  ck_assert(res == ROUGHTIME_SUCCESS);

  uint32_t offset = 0;
  uint32_t length = 0;
  res = get_header_tag(&header, str_to_tag("VER"), &offset, &length);
  ck_assert(res == ROUGHTIME_SUCCESS);

  bool check = check_ver(buf, offset, length - 4, false);
  ck_assert(check);

  /* 33 versions. */
  check = check_ver(buf, offset, length, false);
  ck_assert(!check);
  check = check_ver(buf, offset, length, true);
  ck_assert(!check);

  /* 0 versions. */
  check = check_ver(buf, offset, 0, false);
  ck_assert(!check);

  /* Bad length. */
  check = check_ver(buf, offset, length - 5, false);
  ck_assert(!check);

  /* No matching version. */
  check = check_ver(buf, offset, length - 8, false);
  ck_assert(!check);
  check = check_ver(buf, offset, length - 8, true);
  ck_assert(!check);

  /* Unsorted. */
  SET_UINT32(buf + offset, 1);
  check = check_ver(buf, offset, length - 4, false);
  ck_assert(!check);
  check = check_ver(buf, offset, length - 4, true);
  ck_assert(!check);

  /* Duplicate. */
  SET_UINT32(buf + offset, 0);
  SET_UINT32(buf + offset + 8, 1);
  check = check_ver(buf, offset, length - 4, false);
  ck_assert(!check);

  free(buf);
}
