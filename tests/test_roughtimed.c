/**
 * Used to set a uint32 value in a Roughtime buffer.
 * @param B pointer to the uint32 value.
 * @param V the value to set.
 */
#define SET_UINT32(B, V) {\
  uint32_t tmp = htole32(V);\
  memcpy((B), &tmp, sizeof(uint32_t));\
}

void roughtime_request(uint8_t *nonce, uint8_t *buf, uint32_t *size) {
  ck_assert_ptr_nonnull(nonce);
  ck_assert_ptr_nonnull(buf);
  ck_assert_ptr_nonnull(size);

  roughtime_result_t res = ROUGHTIME_SUCCESS;

  uint32_t type = 0;
  uint32_t ver = ROUGHTIME_VERSION;
  res = create_roughtime_message(
      buf,
      size,
      3,
      "VER",
      4,
      &ver,
      "NONC",
      32,
      nonce,
      "TYPE",
      4,
      &type);
  ck_assert(res == ROUGHTIME_SUCCESS);
}

roughtime_query_t* roughtime_queries(size_t num) {
  roughtime_query_t *queries = calloc(num, sizeof(roughtime_query_t));
  ck_assert_ptr_nonnull(queries);
  uint8_t nonce[32] = {0};
  const char *header = "ROUGHTIM";
  roughtime_result_t res = ROUGHTIME_SUCCESS;
  for (size_t i = 0; i < num; i++) {
    memset(nonce, i & 0xff, 32);
    memcpy(queries[i].msg + 1, header, 8);
    uint32_t size = MAX_RECV_LEN - 9;
    roughtime_request(nonce, queries[i].msg + 9, &size);
    queries[i].len = size + 8;
    uint32_t len = 0;
    roughtime_header_t header = {0};
    res = parse_roughtime_header(queries[i].msg + 9, queries[i].len - 8, &header);
    ck_assert(res == ROUGHTIME_SUCCESS);
    res = get_header_tag(&header, str_to_tag("NONC"), &queries[i].nonc_offset, &len);
    ck_assert(res == ROUGHTIME_SUCCESS);
  }
  return queries;
}

