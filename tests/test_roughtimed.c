/** Checks that sent Roughtime packets have the correct format. */
void check_packets(int num) {
  const char *tags[] = {
    "SIG",
    "NONC",
    "TYPE",
    "PATH",
    "SREP",
    "CERT",
    "INDX",
    NULL
  };
  const char *srep_tags[] = {
    "VER",
    "RADI",
    "MIDP",
    "VERS",
    "ROOT",
    NULL
  };
  const char *cert_tags[] = {
    "SIG",
    "DELE",
    NULL
  };
  const char *dele_tags[] = {
    "PUBK",
    "MINT",
    "MAXT",
    NULL
  };
  roughtime_result_t res = ROUGHTIME_SUCCESS;

  for (int i = 0; i < num; i++) {
    uint8_t *msg = g_sendmmsg_msgs + 1500 * i;
    ck_assert_mem_eq(msg, "ROUGHTIM", 8);
    uint32_t msglen = 0;
    memcpy(&msglen, msg + 8, sizeof(uint32_t));
    ck_assert_uint_eq(msglen, g_sendmmsg_lens[i] - 12);
    roughtime_header_t header = {0};
    res = parse_roughtime_header(msg + 12, g_sendmmsg_lens[i] - 12, &header);
    ck_assert(res == ROUGHTIME_SUCCESS);
    check_header_tags(&header, tags);

    roughtime_header_t srep_header = {0};
    uint32_t srep_offset = 0;
    uint32_t srep_length = 0;
    res = get_header_tag(&header, str_to_tag("SREP"), &srep_offset, &srep_length);
    ck_assert(res == ROUGHTIME_SUCCESS);
    res = parse_roughtime_header(msg + 12 + srep_offset, srep_length, &srep_header);
    ck_assert(res == ROUGHTIME_SUCCESS);
    check_header_tags(&srep_header, srep_tags);

    roughtime_header_t cert_header = {0};
    uint32_t cert_offset = 0;
    uint32_t cert_length = 0;
    res = get_header_tag(&header, str_to_tag("CERT"), &cert_offset, &cert_length);
    ck_assert(res == ROUGHTIME_SUCCESS);
    res = parse_roughtime_header(msg + 12 + cert_offset, cert_length, &cert_header);
    ck_assert(res == ROUGHTIME_SUCCESS);
    check_header_tags(&cert_header, cert_tags);

    roughtime_header_t dele_header = {0};
    uint32_t dele_offset = 0;
    uint32_t dele_length = 0;
    res = get_header_tag(&cert_header, str_to_tag("DELE"), &dele_offset, &dele_length);
    ck_assert(res == ROUGHTIME_SUCCESS);
    res = parse_roughtime_header(msg + 12 + cert_offset + dele_offset, dele_length, &dele_header);
    ck_assert(res == ROUGHTIME_SUCCESS);
    check_header_tags(&dele_header, dele_tags);
  }
}

void run_response_thread(
    thread_arguments_t *args,
    roughtime_query_t *queries,
    int num_queries,
    int expected_packets) {
  ck_assert_ptr_nonnull(args);
  ck_assert_ptr_nonnull(queries);
  ck_assert_int_gt(num_queries, 0);
  pthread_t thread = {0};
  g_quit = false;
  g_sendmmsg_counter = 0;
  memset(g_sendmmsg_msgs, 0, 15000);
  memset(g_sendmmsg_lens, 0, sizeof(size_t) * 10);
  ck_assert_int_eq(pthread_create(&thread, NULL, response_thread, args), 0);
  roughtime_result_t res = add_queries(args, queries, &num_queries);
  ck_assert(res == ROUGHTIME_SUCCESS);
  ck_assert_int_eq(num_queries, 10);

  struct timespec stime = {
    .tv_nsec = 100000000
  };
  nanosleep(&stime, NULL);
  g_quit = true;
  pthread_cond_signal(&args->queue_cond);
  pthread_join(thread, NULL);
  check_packets(expected_packets);
}

