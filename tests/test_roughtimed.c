  ck_assert(res == ROUGHTIME_SUCCESS);
  ck_assert_int_eq(num_queries, 2);
  ck_assert_uint_eq(args.queuep, 4);
  for (int i = 0; i < 4; i++) {
    ck_assert_mem_eq(&args.queue[i], &queries[i & 1], sizeof(roughtime_query_t));
  }

  res = add_queries(&args, queries, &num_queries);
  ck_assert(res == ROUGHTIME_SUCCESS);
  ck_assert_int_eq(num_queries, 1);
  ck_assert_uint_eq(args.queuep, 5);
  for (int i = 0; i < 5; i++) {
    ck_assert_mem_eq(&args.queue[i], &queries[i & 1], sizeof(roughtime_query_t));
  }

